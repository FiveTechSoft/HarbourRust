// Isolated result-to-output contract, not source arithmetic admission.
// x0 payload,x1 format,x2 status,x3 display mode (0 ordinary,1 mixed local).
// validate preserves the four words; error1 is uncaught zero, others exit75.
use super::code::Code;
pub fn emit(c: &mut Code) -> Result<(), String> {
    c.label("result_validate")?;
    c.imm(31, 2, 1, true, true)?;
    c.bc("rt_zero_uncaught", 0)?;
    c.imm(31, 2, 0, true, true)?;
    c.bc("result_bad", 1)?;
    c.imm(31, 3, 1, true, true)?;
    c.bc("result_bad", 8)?;
    c.imm(31, 1, 1, true, true)?;
    c.bc("result_valid", 9)?;
    c.bits(9, 1, 16, 48)?;
    c.imm(31, 9, 10, true, true)?;
    c.bc("result_width_valid", 0)?;
    c.imm(31, 9, 20, true, true)?;
    c.bc("result_bad", 1)?;
    c.label("result_width_valid")?;
    c.bits(9, 1, 0, 16)?;
    c.imm(31, 9, 16, true, true)?;
    c.bc("result_bad", 8)?;
    c.bits(9, 0, 52, 11)?;
    c.imm(31, 9, 2047, true, true)?;
    c.bc("result_bad", 0)?;
    c.label("result_valid")?;
    c.ret();
    c.label("result_print")?;
    c.prologue(32)?;
    c.b("result_validate", true);
    c.imm(31, 1, 0, true, true)?;
    c.bc("result_computed", 0)?;
    c.imm(31, 1, 1, true, true)?;
    c.bc("result_literal", 0)?;
    c.imm(31, 3, 0, true, true)?;
    c.bc("result_ordinary", 0)?;
    c.b("pair_print_mixed", true);
    c.b("result_print_done", false);
    c.label("result_ordinary")?;
    c.b("pair_print_f64", true);
    c.b("result_print_done", false);
    c.label("result_literal")?;
    c.b("rt_i64", true);
    c.b("result_print_done", false);
    c.label("result_computed")?;
    c.b("result_i64", true);
    c.label("result_print_done")?;
    c.epilogue()?;
    c.label("result_bad")?;
    c.mov(0, 75)?;
    c.mov(16, 1)?;
    c.svc();
    c.b("result_bad", false);
    // Computed integer fields use signed decimal length <=10 ? 10 : 20.
    // Different from literal/copy positive width max(10,digits+1).
    c.label("result_i64")?;
    c.prologue(96)?;
    c.copy(9, 0)?;
    c.mov(10, 0)?;
    c.imm(31, 9, 0, true, true)?;
    c.bc("result_abs", 10)?;
    c.mov(10, 1)?;
    c.addsub(9, 31, 9, true, false)?;
    c.label("result_abs")?;
    c.imm(11, 31, 32, false, false)?;
    c.mov(12, 10)?;
    c.label("result_digit")?;
    c.udiv(13, 9, 12)?;
    c.msub(14, 13, 12, 9)?;
    c.imm(14, 14, 48, false, false)?;
    c.imm(11, 11, 1, true, false)?;
    c.byte(14, 11, 0, false)?;
    c.copy(9, 13)?;
    c.imm(31, 9, 0, true, true)?;
    c.bc("result_digit", 1)?;
    c.imm(31, 10, 0, true, true)?;
    c.bc("result_sign_done", 0)?;
    c.mov(14, 45)?;
    c.imm(11, 11, 1, true, false)?;
    c.byte(14, 11, 0, false)?;
    c.label("result_sign_done")?;
    c.imm(9, 31, 32, false, false)?;
    c.addsub(2, 9, 11, true, false)?;
    c.mov(12, 10)?;
    c.imm(31, 2, 10, true, true)?;
    c.bc("result_width_done", 9)?;
    c.mov(12, 20)?;
    c.label("result_width_done")?;
    c.ldst(11, 31, 40, false)?;
    c.ldst(2, 31, 48, false)?;
    c.addsub(1, 12, 2, true, false)?;
    c.adr(0, "rt_spaces")?;
    c.b("rt_write", true);
    c.ldst(0, 31, 40, true)?;
    c.ldst(1, 31, 48, true)?;
    c.b("rt_write", true);
    c.epilogue()
}
