// Own emitted ARM64 ASCII composer prototype, isolated from AST/runtime.
// x0 bits,x1 width10/20,x2 decimals0..435,x3 writable output >=456 bytes.
// x0 output length,x1 status0 success/1 metadata/scratch bound. No syscalls.
// Includes normalizer as a private leaf, no mixed-integral fast path yet.
use super::code::Code;
pub fn emit(c: &mut Code) -> Result<(), String> {
    c.prologue(1024)?;
    for (reg, off) in [(0, 0), (1, 8), (2, 16), (3, 24)] {
        c.ldst(reg, 31, off, false)?;
    }
    c.imm(31, 1, 10, true, true)?;
    c.bc("fmt_width_ok", 0)?;
    c.imm(31, 1, 20, true, true)?;
    c.bc("fmt_bad", 1)?;
    c.label("fmt_width_ok")?;
    c.imm(31, 2, 435, true, true)?;
    c.bc("fmt_bad", 8)?;
    c.b("normalize", true);
    // Store normalized exponent, sign, nonfinite flag. x0 now integer image.
    c.ldst(1, 31, 32, false)?;
    c.ldst(2, 31, 40, false)?;
    c.imm(31, 3, 0, true, true)?;
    c.bc("fmt_stars", 1)?;
    c.imm(9, 31, 64, false, false)?;
    c.imm(9, 9, 16, false, false)?;
    c.mov(10, 16)?;
    c.mov(11, 10)?;
    c.label("fmt_digits")?;
    c.udiv(12, 0, 11)?;
    c.msub(13, 12, 11, 0)?;
    c.imm(13, 13, 48, false, false)?;
    c.imm(9, 9, 1, true, false)?;
    c.byte(13, 9, 0, false)?;
    c.copy(0, 12)?;
    c.imm(10, 10, 1, true, true)?;
    c.bc("fmt_digits", 1)?;
    // intlen=max(exponent+1,1), rawlen=intlen+dec. Reject oversized first.
    c.ldst(9, 31, 32, true)?;
    c.mov(10, 1)?;
    c.imm(31, 9, 0, true, true)?;
    c.bc("fmt_intlen", 11)?;
    c.imm(10, 9, 1, false, false)?;
    c.label("fmt_intlen")?;
    c.ldst(10, 31, 48, false)?;
    c.ldst(11, 31, 16, true)?;
    c.addsub(12, 10, 11, false, false)?;
    c.ldst(12, 31, 56, false)?;
    c.imm(31, 12, 456, true, true)?;
    c.bc("fmt_bad", 8)?;
    // raw digits, including one round-source digit, at stack+96.
    c.mov(10, 0)?;
    c.label("fmt_seq")?;
    c.ldst(9, 31, 32, true)?;
    c.copy(11, 10)?;
    c.mov(13, 48)?;
    c.imm(31, 9, 0, true, true)?;
    c.bc("fmt_index", 10)?;
    c.imm(31, 10, 0, true, true)?;
    c.bc("fmt_source_done", 0)?;
    c.addsub(11, 10, 9, false, false)?;
    c.label("fmt_index")?;
    c.imm(31, 11, 0, true, true)?;
    c.bc("fmt_source_done", 11)?;
    c.imm(31, 11, 16, true, true)?;
    c.bc("fmt_source_done", 2)?;
    c.imm(14, 31, 64, false, false)?;
    c.addsub(14, 14, 11, false, false)?;
    c.byte(13, 14, 0, true)?;
    c.label("fmt_source_done")?;
    c.imm(14, 31, 96, false, false)?;
    c.addsub(14, 14, 10, false, false)?;
    c.byte(13, 14, 0, false)?;
    c.ldst(12, 31, 56, true)?;
    c.addsub(31, 10, 12, true, true)?;
    c.bc("fmt_seq_done", 0)?;
    c.imm(10, 10, 1, false, false)?;
    c.b("fmt_seq", false);
    c.label("fmt_seq_done")?;
    c.mov(15, 0)?; // extra leading digit on full carry
    c.imm(31, 13, 53, true, true)?;
    c.bc("fmt_round_done", 3)?;
    c.copy(10, 12)?;
    c.label("fmt_carry")?;
    c.imm(10, 10, 1, true, false)?;
    c.imm(14, 31, 96, false, false)?;
    c.addsub(14, 14, 10, false, false)?;
    c.byte(13, 14, 0, true)?;
    c.imm(31, 13, 57, true, true)?;
    c.bc("fmt_raise", 1)?;
    c.mov(13, 48)?;
    c.byte(13, 14, 0, false)?;
    c.imm(31, 10, 0, true, true)?;
    c.bc("fmt_carry", 1)?;
    c.mov(15, 1)?;
    c.ldst(10, 31, 48, true)?;
    c.imm(10, 10, 1, false, false)?;
    c.ldst(10, 31, 48, false)?;
    c.b("fmt_round_done", false);
    c.label("fmt_raise")?;
    c.imm(13, 13, 1, false, false)?;
    c.byte(13, 14, 0, false)?;
    c.label("fmt_round_done")?;
    c.ldst(15, 31, 80, false)?;
    // total=rawlen+extra+sign+(dec?1:0), field=width+(dec?1+dec:0).
    c.ldst(12, 31, 56, true)?;
    c.addsub(12, 12, 15, false, false)?;
    c.ldst(9, 31, 40, true)?;
    c.addsub(12, 12, 9, false, false)?;
    c.ldst(10, 31, 8, true)?;
    c.ldst(11, 31, 16, true)?;
    c.imm(31, 11, 0, true, true)?;
    c.bc("fmt_no_dot_size", 0)?;
    c.imm(12, 12, 1, false, false)?;
    c.addsub(10, 10, 11, false, false)?;
    c.imm(10, 10, 1, false, false)?;
    c.label("fmt_no_dot_size")?;
    c.imm(31, 12, 456, true, true)?;
    c.bc("fmt_bad", 8)?;
    c.ldst(3, 31, 24, true)?;
    c.copy(4, 3)?;
    c.addsub(10, 10, 12, true, true)?;
    c.bc("fmt_sign", 13)?;
    c.mov(13, 32)?;
    c.label("fmt_pad")?;
    c.byte(13, 4, 0, false)?;
    c.imm(4, 4, 1, false, false)?;
    c.imm(10, 10, 1, true, true)?;
    c.bc("fmt_pad", 1)?;
    c.label("fmt_sign")?;
    c.ldst(9, 31, 40, true)?;
    c.imm(31, 9, 0, true, true)?;
    c.bc("fmt_prefix", 0)?;
    c.mov(13, 45)?;
    c.byte(13, 4, 0, false)?;
    c.imm(4, 4, 1, false, false)?;
    c.label("fmt_prefix")?;
    c.mov(10, 0)?; // output digit position
    c.ldst(15, 31, 80, true)?;
    c.imm(31, 15, 0, true, true)?;
    c.bc("fmt_copy", 0)?;
    c.mov(13, 49)?;
    c.byte(13, 4, 0, false)?;
    c.imm(4, 4, 1, false, false)?;
    c.mov(10, 1)?;
    c.label("fmt_copy")?;
    c.ldst(9, 31, 48, true)?;
    c.addsub(31, 10, 9, true, true)?;
    c.bc("fmt_not_dot", 1)?;
    c.ldst(11, 31, 16, true)?;
    c.imm(31, 11, 0, true, true)?;
    c.bc("fmt_not_dot", 0)?;
    c.mov(13, 46)?;
    c.byte(13, 4, 0, false)?;
    c.imm(4, 4, 1, false, false)?;
    c.label("fmt_not_dot")?;
    c.ldst(12, 31, 56, true)?;
    c.addsub(12, 12, 15, false, false)?;
    c.addsub(31, 10, 12, true, true)?;
    c.bc("fmt_complete", 0)?;
    c.addsub(11, 10, 15, true, false)?;
    c.imm(14, 31, 96, false, false)?;
    c.addsub(14, 14, 11, false, false)?;
    c.byte(13, 14, 0, true)?;
    c.byte(13, 4, 0, false)?;
    c.imm(4, 4, 1, false, false)?;
    c.imm(10, 10, 1, false, false)?;
    c.b("fmt_copy", false);
    c.label("fmt_complete")?;
    c.addsub(0, 4, 3, true, false)?;
    c.mov(1, 0)?;
    c.epilogue()?;
    c.label("fmt_stars")?;
    c.ldst(10, 31, 8, true)?;
    c.ldst(11, 31, 16, true)?;
    c.imm(31, 11, 0, true, true)?;
    c.bc("fmt_stars_count", 0)?;
    c.addsub(10, 10, 11, false, false)?;
    c.imm(10, 10, 1, false, false)?;
    c.label("fmt_stars_count")?;
    c.copy(0, 10)?;
    c.ldst(4, 31, 24, true)?;
    c.mov(13, 42)?;
    c.label("fmt_stars_loop")?;
    c.byte(13, 4, 0, false)?;
    c.imm(4, 4, 1, false, false)?;
    c.imm(10, 10, 1, true, true)?;
    c.bc("fmt_stars_loop", 1)?;
    c.mov(1, 0)?;
    c.epilogue()?;
    c.label("fmt_bad")?;
    c.mov(0, 0)?;
    c.mov(1, 1)?;
    c.epilogue()?;
    c.label("normalize")?;
    super::decimal::emit(c)
}
