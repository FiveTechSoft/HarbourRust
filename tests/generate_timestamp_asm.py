#!/usr/bin/env python3
"""Generate the timestamp scalar helper from runtime/hrtimestamp.c.

Same recipe as the other clean-room C blobs: SysV, freestanding, and
the blob's external whitelist.
"""
from pathlib import Path
import subprocess,re,hashlib,json,os,ast
root=Path(__file__).resolve().parents[1]
cc=os.environ.get('HR_TIMESTAMP_CC',str(root/'tools/mingw/mingw64/bin/gcc.exe'))
if not Path(cc).exists(): cc='gcc'
src='runtime/hrtimestamp.c'
flags=['-D_WIN64','-std=c99','-O2','-S','-mabi=sysv','-ffreestanding','-fno-builtin','-fno-stack-protector','-fno-asynchronous-unwind-tables','-fno-unwind-tables','-fno-ident','-mno-red-zone','-fno-pic','-fno-tree-vectorize','-mno-stack-arg-probe','-minline-all-stringops','-mstringop-strategy=rep_byte','-fno-jump-tables','-mno-push-args','-fcf-protection=none','-Wall','-Wextra','-Werror','-Wno-misleading-indentation']
allowed={'hbc_alloc','hbc_stod','hbc_date_days','hbc_date_from_days','hbc_date_core_c'}
raw=root/'generated/hrtimestamp.raw.s';subprocess.run([cc,*flags,src,'-o',str(raw)],cwd=root,check=True)
raw_bytes=root/'generated/hrtimestamp.raw.s'
# the host gcc emits host-native line endings; normalize the assembly to LF
raw_bytes.write_bytes(raw_bytes.read_bytes().replace(b'\r\n', b'\n'))
if b'\r' in raw_bytes.read_bytes(): raise ValueError('gcc output must not carry CR bytes')
s=raw_bytes.read_text();raw.unlink()
s=re.sub(r'^\s*\.(file|def|ident|type|size)\s+.*\n','',s,flags=re.M)
s=re.sub(r'^\s*\.section\s+\.note\.[^\n]*\n','',s,flags=re.M)
s=re.sub(r'\.L([A-Za-z0-9_.$]+)',r'.Lhtimestamp_\1',s)
s=s.replace('movabsq','movabs')
s=re.sub(r'call\s+\*(hbc_alloc)@GOTPCREL\(%rip\)',r'call \1',s)  # -fPIE gives RIP-relative data; keep the direct call of the -fno-pic recipe
s=re.sub(r'^(\s*(?:sal|sar|shl|shr|rol|ror)[bwlq]?)\s+(%\w+)\s*$',r'\1 $1, \2',s,flags=re.M)
s=re.sub(r'^\s*\.(?:lcomm|comm)\s+([A-Za-z_][\w.]*),(\d+)(?:,\s*\d+)?\s*$',lambda m:'\n.bss\n.balign '+m[2]+'\n'+m[1]+':\n.zero '+m[2]+'\n.text',s,flags=re.M)
s=re.sub(r'^\s*\.local\s+[A-Za-z_][\w.]*\s*\n','',s,flags=re.M)  # ELF gcc: .local precedes .comm
s=re.sub(r'^\s*\.(string|ascii)\s+("(?:[^"\\]|\\.)*")\s*$',lambda m:(lambda bs:('.byte '+','.join(map(str,bs))) if bs else '')(list(ast.literal_eval('b'+m[2]))+([0] if m[1]=='string' else [])),s,flags=re.M)  # .string adds NUL, .ascii does not; empty -> nothing
s=re.sub(r'^\s*\.section\s+\.(?:rodata|rdata)[^\n]*', '@HRTIMESTAMP_RODATA@', s, flags=re.M)
for name in re.findall(r'^([A-Za-z_][A-Za-z0-9_.$]*):',s,re.M):
    if not name.startswith(('hbc_ts_',)):s=re.sub(r'(?<![A-Za-z0-9_.])'+re.escape(name)+r'(?![A-Za-z0-9_.$])','htimestamp_local_'+name,s)
labels=set(re.findall(r'^([A-Za-z_.$][A-Za-z0-9_.$]*):',s,re.M))
calls=set(re.findall(r'\b(?:call|jmp)\s+([A-Za-z_][A-Za-z0-9_.$]*)',s))
externals={c for c in calls if c not in labels}
assert externals<=allowed,(externals-allowed)
assert not re.search(r'^[^#\n]*[A-Za-z_.$][\w.$]*\(,%',s,re.M),'absolute indexed symbol address (PE truncates it)'
assert not re.search(r'__chkstk|memcpy|memset|PLT|GOT|\.seh|\.cfi|\.eh_frame',s),s
out=root/'generated/hrtimestamp.s'
out.write_bytes(('# GENERATED by tests/generate_date_asm.py from runtime/hrtimestamp.c - do not edit.\n.text\n'+s+'\n.text\n').encode('utf-8'))
(root/'generated/hrtimestamp_recipe.json').write_bytes((json.dumps(dict(section_policy='@HRTIMESTAMP_RODATA@ expands only at timestamp inclusion: Linux .rodata; Windows .rdata,"r"',newline_policy='LF bytes; CR rejected in source; assembly emitted as UTF-8 LF',compiler=subprocess.check_output([cc,'--version'],text=True).splitlines()[0],flags=flags,source_sha256=hashlib.sha256((root/src).read_bytes()).hexdigest(),asm_sha256=hashlib.sha256(out.read_bytes()).hexdigest(),external_calls=sorted(externals)),indent=2)+'\n').encode('utf-8'))
print('generated',len(labels),'labels; externals',sorted(externals))
