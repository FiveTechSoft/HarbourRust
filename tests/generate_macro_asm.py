#!/usr/bin/env python3
"""Generate generated/hrmacro.s from runtime/hrmacro.c (developer-only).

The evaluator has no OS dependency, so ONE SysV-ABI build serves every
x86-64 target: hbc's internal helper convention is SysV on Linux, Windows
and Mach-O alike. Any GCC that accepts -mabi=sysv works; on Windows the
bundled MinGW is used (HR_MACRO_CC overrides). Section directives become
the @HRM_RODATA@ placeholder that hbc resolves per target.
"""
from pathlib import Path
import subprocess, re, json, hashlib, os, ast

root = Path(__file__).resolve().parents[1]
cc = os.environ.get('HR_MACRO_CC') or str(root / 'tools/mingw/mingw64/bin/gcc.exe')
if not Path(cc).exists():
    cc = 'gcc'
flags = ['-std=c99', '-O2', '-S', '-mabi=sysv', '-ffreestanding', '-fno-builtin',
         '-fno-stack-protector', '-fno-asynchronous-unwind-tables', '-fno-unwind-tables',
         '-fno-ident', '-mno-red-zone', '-fno-pic', '-mcmodel=large', '-fno-jump-tables', '-mno-push-args', '-fcf-protection=none', '-Wall', '-Wextra', '-Werror',
         '-Wno-misleading-indentation']
src = 'runtime/hrmacro_embedded.c'
raw = root / 'generated/hrmacro.raw.s'
out = root / 'generated/hrmacro.s'
subprocess.run([cc, *flags, src, '-o', str(raw)], cwd=root, check=True)
s = raw.read_text()
s = re.sub(r'^\s*\.section\s+\.note\.GNU-stack[^\n]*$', '', s, flags=re.M)
raw.unlink()
s = re.sub(r'^\s*\.(file|def|ident|type|size)\s+.*\n', '', s, flags=re.M)
s = re.sub(r'^\s*\.section\s+\.(rdata|rodata)[^\n]*$', '\t@HRM_RODATA@', s, flags=re.M)
s = re.sub(r'\.L([A-Za-z0-9_.$]+)', r'.Lhrm_\1', s)
s = re.sub(r'(?<![A-Za-z0-9_.])(\d+)\+([A-Za-z_.$][A-Za-z0-9_.$]*)', r'\2+\1', s)
s = re.sub(r'^(\s*(?:sal|sar|shl|shr|rol|ror)[bwlq]?)\s+(%\w+)\s*$', r'\1 $1, \2', s, flags=re.M)
s = s.replace('movabsq', 'movabs')
# Exact encoding, REP STOSQ = F3 48 AB.
s = re.sub(r'^\s*rep stosq\s*$', '\t.byte 243,72,171', s, flags=re.M)
s = re.sub(r'^\s*\.lcomm\s+([A-Za-z_][A-Za-z0-9_]*)\s*,\s*(\d+)(?:\s*,\s*\d+)?\s*$',
           r'\t.section .data\n\1:\n\t.zero \2\n\t.section .text', s, flags=re.M)
s = re.sub(r'^\s*\.(ascii|string)\s+(".*")\s*$',
           lambda m: '\t.byte ' + ','.join(str(b) for b in (ast.literal_eval('b' + m[2])+(b'\0' if m[1]=='string' else b''))), s, flags=re.M)
# Static C functions get a private prefix; only hrmacro_eval is exported.
for label in re.findall(r'^([A-Za-z_.$][A-Za-z0-9_.$]*):', s, re.M):
    if not label.startswith(('hrmacro_', 'hrmv_', 'hrmb_', '.Lhrm_')):
        s = re.sub(r'(?<![A-Za-z0-9_.])' + re.escape(label) + r'(?![A-Za-z0-9_.$])', 'hrm_local_' + label, s)
labels = re.findall(r'^([A-Za-z_.$][A-Za-z0-9_.$]*):', s, re.M)
assert len(labels) == len(set(labels))
assert all(l.startswith(('hrmacro_', 'hrmv_', 'hrmb_', 'hrm_local_', '.Lhrm_')) for l in labels), labels
calls = set(re.findall(r'\b(?:call|jmp)\s+([A-Za-z_][A-Za-z0-9_]*)', s)) | set(re.findall(r'\bhrm_(?:alloc|free|float|exp|log|fail|builtin_fail|raw_alloc|raw_free|export_string|export_float)\b',s))
external = sorted(c for c in calls if not c.startswith(('hrm_local_', 'hrmacro_', 'hrmv_', 'hrmb_')))
assert set(external) <= {'hrm_alloc', 'hrm_free', 'hrm_float', 'hrm_exp', 'hrm_log', 'hrm_fail', 'hrm_raw_alloc', 'hrm_raw_free', 'hrm_export_string', 'hrm_export_float', 'hrm_builtin_fail'}, external
assert not re.search(r'__chkstk|__stack_chk|memcpy|memset|GOT|PLT|\.seh|\.cfi|\.eh_frame', s)
header = ('# GENERATED by tests/generate_macro_asm.py from runtime/hrmacro_embedded.c and B1 dependencies - do not edit.\n'
          '# SysV ABI, shared by every x86-64 target; hbc resolves the rodata placeholder.\n'
          '\t.text\n')
out.write_text(header + s + '\t.text\n', newline='\n')
version = subprocess.check_output([cc, '--version'], text=True).splitlines()[0]
recipe = {
    'compiler': version,
    'flags': flags,
    'source_sha256': hashlib.sha256((root / src).read_bytes()).hexdigest(),
    'source_dependencies_sha256': {name:hashlib.sha256((root/name).read_bytes()).hexdigest() for name in sorted(set(subprocess.check_output([cc,*flags,'-MM',src],cwd=root,text=True).replace('\\\n',' ').split(':',1)[1].split()))},
    'asm_sha256': hashlib.sha256(out.read_bytes()).hexdigest(),
    'external_calls': external,
}
(root / 'generated/hrmacro_recipe.json').write_text(json.dumps(recipe, indent=2) + '\n', newline='\n')
print('ok', out, len(labels), 'labels', external)
