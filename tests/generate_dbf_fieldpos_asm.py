#!/usr/bin/env python3
"""Generate generated/hrdbf_fieldpos.s (developer-only step).

runtime/hrdbf_fieldpos.c is freestanding and OS-free, compiled with hbc's
internal SysV ABI for every target (same convention as hrmacro.s), so one
blob serves the Windows and Linux DBF adapters. Set HR_FIELDPOS_CC to a
MinGW-w64 or Linux x86-64 gcc.
"""
from pathlib import Path
import os, re, subprocess
root = Path(__file__).resolve().parents[1]
cc = os.environ.get('HR_FIELDPOS_CC', 'gcc')
flags = ['-std=c99', '-O2', '-S', '-ffreestanding', '-fno-builtin', '-fno-stack-protector',
         '-fno-asynchronous-unwind-tables', '-fno-unwind-tables', '-fno-ident', '-mno-red-zone',
         '-mabi=sysv', '-D_WIN64', '-mcmodel=small', '-fno-pic', '-fno-tree-vectorize', '-Wall', '-Wextra', '-Werror']
raw = root / 'generated/hrdbf_fieldpos.raw.s'
subprocess.run([cc, *flags, 'runtime/hrdbf_fieldpos.c', '-o', str(raw)], cwd=root, check=True)
s = raw.read_text()
raw.unlink()
s = re.sub(r'^\s*\.(file|def|ident|size|type|section\s+\.note\S*|seh_\w+)\b.*\n', '', s, flags=re.M)
s = re.sub(r'^\s*\.(scl|endef)\b.*\n', '', s, flags=re.M)
s = re.sub(r'\.L([A-Za-z0-9_.$]+)', r'.Lhrdbffp_\1', s)
s = re.sub(r'^\s*\.(section\s+\.text\S*|text)\b.*$', '\t.text', s, flags=re.M)
labels = re.findall(r'^([A-Za-z_.$][A-Za-z0-9_.$]*):', s, re.M)
for label in labels:
    if label != 'hrdbf_app_fieldpos' and not label.startswith('.Lhrdbffp_'):
        s = re.sub(r'(?<![A-Za-z0-9_.$])' + re.escape(label) + r'(?![A-Za-z0-9_.$])', 'hrdbffp_local_' + label, s)
assert not re.search(r'__chkstk|__stack_chk|GOT|PLT|\.seh|\.cfi|@', s), s
s = '# Generated by tests/generate_dbf_fieldpos_asm.py from runtime/hrdbf_fieldpos.c. Do not edit.\n' + s
(root / 'generated/hrdbf_fieldpos.s').write_text(s, newline='\n')
print('ok', len(s))
