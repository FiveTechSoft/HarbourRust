#!/usr/bin/env python3
"""Generate the TRANSFORM layout helper from runtime/hrtransform.c (own MIT C)."""
from pathlib import Path
import subprocess, re, hashlib, json, os
root = Path(__file__).resolve().parents[1]
cc = os.environ.get('HR_TRANSFORM_CC', 'gcc')
src = 'runtime/hrtransform.c'
flags = ['-std=c99', '-O2', '-S', '-ffreestanding', '-fno-builtin', '-fno-stack-protector',
         '-fno-asynchronous-unwind-tables', '-fno-unwind-tables', '-fno-ident', '-mno-red-zone',
         '-fno-pic', '-mno-sse', '-mno-mmx', '-fno-tree-vectorize', '-minline-all-stringops',
         '-mstringop-strategy=rep_byte', '-fno-jump-tables', '-fno-tree-switch-conversion', '-mno-push-args',
         '-fcf-protection=none', '-Wall', '-Wextra', '-Werror']
raw = root / 'generated/hrtransform.raw.s'
subprocess.run([cc, *flags, src, '-o', str(raw)], cwd=root, check=True)
s = raw.read_text(); raw.unlink()
s = re.sub(r'^\s*\.(file|def|ident|type|size|section\s+\.note.*)\s*.*\n', '', s, flags=re.M)
s = re.sub(r'\.L([A-Za-z0-9_.$]+)', r'.Lhrtr_\1', s)
s = s.replace('movabsq', 'movabs')
s = re.sub(r'^(\s*(?:sal|sar|shl|shr|rol|ror)[bwlq]?)\s+(%\w+)\s*$', r'\1 $1, \2', s, flags=re.M)
for name in re.findall(r'^([A-Za-z_][A-Za-z0-9_.$]*):', s, re.M):
    if name not in ('hbc_tr_dims', 'hbc_tr_apply'):
        s = re.sub(r'(?<![A-Za-z0-9_.])' + re.escape(name) + r'(?![A-Za-z0-9_.$])', 'hrtransform_local_' + name, s)
labels = set(re.findall(r'^([A-Za-z_.$][A-Za-z0-9_.$]*):', s, re.M))
calls = set(re.findall(r'\b(?:call|jmp)\s+([A-Za-z_][A-Za-z0-9_.$]*)', s))
assert calls <= labels, (calls - labels)
assert not re.search(r'__chkstk|memcpy|memset|PLT|GOT|\.seh|\.cfi', s)
out = root / 'generated/hrtransform.s'
out.write_text('# GENERATED by tests/generate_transform_asm.py; original MIT C.\n.text\n' + s + '\n.text\n')
(root / 'generated/hrtransform_recipe.json').write_text(json.dumps(dict(
    compiler=subprocess.check_output([cc, '--version'], text=True).splitlines()[0], flags=flags,
    source_sha256=hashlib.sha256((root / src).read_bytes()).hexdigest(),
    asm_sha256=hashlib.sha256(out.read_bytes()).hexdigest(),
    external_calls=sorted(calls - labels)), indent=2) + '\n')
print('generated', len(labels), 'labels')
