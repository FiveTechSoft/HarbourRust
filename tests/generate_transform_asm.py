#!/usr/bin/env python3
"""Generate the TRANSFORM numeric helper from runtime/hrtransform.c.

Same pinned flags as generate_sha1_asm.py minus the SSE ban (the helper
formats doubles through xmm0). Local regeneration uses the repository
MinGW; the CI can pin another compiler through HR_TRANSFORM_CC.
"""
from pathlib import Path
import subprocess,re,hashlib,json,os,ast
root=Path(__file__).resolve().parents[1]
cc=os.environ.get('HR_TRANSFORM_CC',str(root/'tools/mingw/mingw64/bin/gcc.exe'))
if not Path(cc).exists(): cc='gcc'
src='runtime/hrtransform.c'
flags=['-D_WIN64','-std=c99','-O2','-S','-mabi=sysv','-ffreestanding','-fno-builtin','-fno-stack-protector','-fno-asynchronous-unwind-tables','-fno-unwind-tables','-fno-ident','-mno-red-zone','-fno-pic','-fno-tree-vectorize','-mno-stack-arg-probe','-minline-all-stringops','-mstringop-strategy=rep_byte','-fno-jump-tables','-mno-push-args','-fcf-protection=none','-Wall','-Wextra','-Werror','-Wno-misleading-indentation']
raw=root/'generated/hrtransform.raw.s';subprocess.run([cc,*flags,src,'-o',str(raw)],cwd=root,check=True)
s=raw.read_text();raw.unlink()
s=re.sub(r'^\s*\.(file|def|ident|type|size)\s+.*\n','',s,flags=re.M)
s=re.sub(r'\.L([A-Za-z0-9_.$]+)',r'.Lhrt_\1',s)
s=s.replace('movabsq','movabs')
s=re.sub(r'^(\s*(?:sal|sar|shl|shr|rol|ror)[bwlq]?)\s+(%\w+)\s*$',r'\1 $1, \2',s,flags=re.M)
s=re.sub(r'^\s*\.(?:lcomm|comm)\s+(\S+),(\d+)(?:,\s*\d+)?\s*$',lambda m:'\n.bss\n.balign 16\n'+m[1]+':\n.zero '+m[2]+'\n.text',s,flags=re.M)
s=re.sub(r'^\s*\.(?:string|ascii)\s+("(?:[^"\\]|\\.)*")\s*$',lambda m:'.byte '+','.join(str(b)for b in ast.literal_eval('b'+m[1])),s,flags=re.M)
for name in re.findall(r'^([A-Za-z_][A-Za-z0-9_.$]*):',s,re.M):
    if not name.startswith('hbc_transform'):s=re.sub(r'(?<![A-Za-z0-9_.])'+re.escape(name)+r'(?![A-Za-z0-9_.$])','hrt_local_'+name,s)
labels=set(re.findall(r'^([A-Za-z_.$][A-Za-z0-9_.$]*):',s,re.M))
calls=set(re.findall(r'\b(?:call|jmp)\s+([A-Za-z_][A-Za-z0-9_.$]*)',s))
assert calls<=labels|(calls&{'hbc_alloc','hbc_freestr'}),(calls-labels)
assert not re.search(r'__chkstk|memcpy|memset|PLT|GOT|\.seh|\.cfi|\.eh_frame',s),s
out=root/'generated/hrtransform.s'
out.write_text('# GENERATED by tests/generate_transform_asm.py from runtime/hrtransform.c - do not edit.\n.text\n'+s+'\n.text\n')
(root/'generated/hrtransform_recipe.json').write_text(json.dumps(dict(compiler=subprocess.check_output([cc,'--version'],text=True).splitlines()[0],flags=flags,source_sha256=hashlib.sha256((root/src).read_bytes()).hexdigest(),asm_sha256=hashlib.sha256(out.read_bytes()).hexdigest(),external_calls=sorted(c for c in calls if c not in labels)),indent=2)+'\n')
print('generated',len(labels),'labels; externals',sorted(c for c in calls if c not in labels))
